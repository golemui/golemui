import { defineForm } from '@formforge/core';

export const signin = defineForm({
  states: {
    register: '$form.registerMode === true',
    'register:adult': '$form.user.age >= 18',
    'register:minor': '$form.user.age < 18',
    'register:minor:tall': '$form.user.height > 180',
    termsAccepted: '$form.terms === true',
  },
  form: {
    uid: '',
    kind: 'layout',
    widget: 'stack',
    children: [
      {
        uid: '',
        kind: 'control',
        widget: 'textinput',
        path: 'user.email',
        disabled: true,
        required: true,
        defaultValue: 'joan@joan.com',
      },
      {
        uid: '',
        kind: 'control',
        widget: 'textinput',
        'label.register': 'Password 1',
        path: 'user.password',
        required: true,
        on: { 'change.register': 'checkPasswordMatch' },
      },
      {
        uid: '',
        kind: 'control',
        widget: 'textinput',
        label: 'Confirm Password',
        path: 'confirm',
        on: { change: 'checkPasswordMatch' },
        include: { in: ['register'] },
      },
      {
        uid: '',
        kind: 'control',
        widget: 'textinput',
        path: 'user.age',
        defaultValue: 0,
        required: true,
      },
      {
        uid: '',
        kind: 'control',
        widget: 'textinput',
        path: 'user.height',
        defaultValue: '170',
        required: true,
      },
      {
        uid: '',
        kind: 'control',
        widget: 'checkbox',
        path: 'user.playBasketball',
        include: { in: ['register:minor:tall'] },
      },
      {
        uid: '',
        kind: 'control',
        widget: 'checkbox',
        label: 'Register',
        path: 'registerMode',
      },
      {
        uid: '',
        kind: 'control',
        widget: 'checkbox',
        label: 'Accept Terms',
        path: 'terms',
        include: { in: ['register'] },
      },
      {
        uid: '',
        kind: 'button',
        widget: 'button',
        label: 'Login',
        'label.register': 'Register',
        disabled: false,
        'disabled.register': true,
        'disabled.termsAccepted': false,
        on: {
          click: 'handleLogin',
          'click.register': 'handleRegister',
        },
      },
    ],
  },
});
