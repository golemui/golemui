/**
 * Generates `skills/golemui/widgets-index.md`, the agent skill's index of JSON widget types,
 * from the MCP's JSON registry (`listWidgetTypes`, `getWidgetSpec`), the same source as
 * `json_get_widget_spec`, so the skill and the MCP can never disagree. CI regenerates it and
 * fails when it differs from the committed file.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { DX_SPECS, listDxFactories } from '../src/dx/dx-specs';
import { getWidgetSpec, listWidgetTypes } from '../src/json/get-widget-spec';

const here = dirname(fileURLToPath(import.meta.url));
const REPO = join(here, '..', '..', '..', '..');

const DOCS_BASE = 'https://golemui.com';

const GENERATED_HEADER =
  '<!-- GENERATED by libs/gui/mcp/tools/generate-skill-refs.ts from the JSON widget registry\n' +
  '     of libs/gui/mcp/src/json/get-widget-spec.ts — DO NOT EDIT. Regenerate with\n' +
  '     `npm run generate:skill`. -->';

type Kind = 'input' | 'action' | 'display' | 'layout';

const GROUPS: Record<Kind, { title: string; docGroup: string }> = {
  input: { title: 'Input widgets', docGroup: 'input-fields' },
  action: { title: 'Action widgets', docGroup: 'interactive-fields' },
  display: { title: 'Display widgets', docGroup: 'display-fields' },
  layout: { title: 'Layout widgets', docGroup: 'layout-fields' },
};

/**
 * The docs slug of the types whose page name does not follow from the type. Every other type
 * takes the slug of the `gui.*` factory whose slug is the type in lower case or kebab case.
 */
const SLUG_OVERRIDES: Record<string, string> = {
  flex: 'flex',
  markdownText: 'markdown-text',
  rangeDateTimeCalendar: 'range-datetime-calendar',
  rangeDateTimeInput: 'range-datetime-input',
  rangeDateTimePicker: 'range-datetime-picker',
};

const kebab = (type: string) => type.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

/** The docs slug of a JSON widget type. Throws for a type no rule covers. */
function docSlug(type: string): string {
  if (SLUG_OVERRIDES[type]) return SLUG_OVERRIDES[type];
  const slugs = new Set(listDxFactories().map((f) => DX_SPECS[f].docSlug));
  for (const candidate of [type.toLowerCase(), kebab(type)]) {
    if (slugs.has(candidate)) return candidate;
  }
  throw new Error(
    `No docs page for the widget type \`${type}\`. Add it to SLUG_OVERRIDES in generate-skill-refs.ts.`,
  );
}

export function buildWidgetsIndex(): string {
  const rows: Record<Kind, string[]> = { input: [], action: [], display: [], layout: [] };
  for (const type of listWidgetTypes()) {
    const spec = getWidgetSpec({ widgetType: type });
    const kind = spec.kind as Kind;
    if (!GROUPS[kind]) {
      throw new Error(`The widget type \`${type}\` has an unknown kind \`${spec.kind}\`.`);
    }
    const url = `${DOCS_BASE}/json/widgets-reference/${GROUPS[kind].docGroup}/${docSlug(type)}.md`;
    const deprecated = (spec.schema as { deprecated?: boolean }).deprecated
      ? ' (deprecated: do not use)'
      : '';
    rows[kind].push(`- \`${type}\`${deprecated} — ${url}`);
  }

  const lines: string[] = [GENERATED_HEADER, '', '# GolemUI — widgets index', ''];
  lines.push(
    'Every widget `type` of a JSON definition, by `kind`, with its docs page: props, examples ' +
      'and CSS variables. With the MCP, `json_get_widget_spec` returns the same props as JSON. ' +
      `The full docs index is ${DOCS_BASE}/llms.txt.`,
  );
  lines.push('');
  for (const kind of ['input', 'action', 'display', 'layout'] as const) {
    lines.push(`## ${GROUPS[kind].title}`, '');
    lines.push(...rows[kind]);
    lines.push(
      `- Overview — ${DOCS_BASE}/json/widgets-reference/${GROUPS[kind].docGroup}/overview.md`,
      '',
    );
  }
  return lines.join('\n');
}

/**
 * Formats the generated file with the repository prettier config. The committed file is
 * prettier-formatted, so the CI check that regenerates it only passes when the generator
 * writes the same formatting.
 */
async function formatMarkdown(content: string, filePath: string): Promise<string> {
  const options = await resolveConfig(filePath);
  if (options === null) {
    throw new Error(`No prettier config found for ${filePath}`);
  }
  return format(content, { ...options, filepath: filePath });
}

const widgetsIndexPath = join(REPO, 'skills', 'golemui', 'widgets-index.md');
const widgetsIndex = await formatMarkdown(buildWidgetsIndex() + '\n', widgetsIndexPath);
writeFileSync(widgetsIndexPath, widgetsIndex, 'utf-8');

console.log(
  `Wrote widgets-index.md (${widgetsIndex.length} bytes) — ${listWidgetTypes().length} widget types.`,
);
