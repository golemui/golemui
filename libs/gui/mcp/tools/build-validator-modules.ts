/**
 * Builds the generated validator modules with ajv standalone code, so no entry compiles a schema
 * at runtime: Workers and pages under a strict CSP reject the `new Function` call that ajv
 * compiles with. The generator script writes the result. The modules are not committed because
 * they are large and ajv renumbers its functions on any schema change. The nx target
 * `generate-validators` builds them before `build` and `vite:test`.
 *
 * Layout of the generated directory:
 *   - one module per validator (`root.js`, `chunk-ref.js`, `shallow/<widgetType>.js`,
 *     `branch/<definitionKey>.js`, `custom/<kind>.js`), each exporting `validate`;
 *   - `shared.js`, the code two or more of them contain (see `share-declarations.ts`);
 *   - `metadata.js`, what the walk needs to know about the schemas;
 *   - `sync.js`, static imports of every validator, for the `json` entry;
 *   - `lazy.js`, a loader per validator, for the `json-lazy` entry;
 *   - `testing/form-validator.js`, the whole-form validator, for the differential test only.
 * The `.d.ts` files next to them are hand-written and committed.
 */
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { ALL_SCHEMAS, FORM_SCHEMA } from '../src/json/schemas/index';
import {
  planStandaloneValidators,
  planValidatorMetadata,
  stripAnnotations,
  type StandaloneValidatorPlan,
} from '../src/json/schemas/validator-schemas';
import { shareDeclarations, type StandaloneModule } from './share-declarations';

export const GENERATED_HEADER =
  '// GENERATED by libs/gui/mcp/tools/generate-validators.ts - DO NOT EDIT.\n' +
  '// Regenerate with `npm run generate:validators`.\n';

/** Module path (relative, without extension) -> JavaScript source. */
export type ValidatorModules = Map<string, string>;

/** The functions and schema constants that two or more validator modules use. */
const SHARED_MODULE_PATH = 'shared';

const MODULE_PATH_PATTERN = /^[a-z]+(?:-[a-z]+)*(?:\/[A-Za-z][A-Za-z0-9]*)?$/;

/**
 * Generates every module of the generated directory.
 * @returns The source of each module, keyed by its path without the `.js` extension.
 */
export function buildValidatorModules(): ValidatorModules {
  const plan = planStandaloneValidators(FORM_SCHEMA);
  assertModulePaths(plan);
  assertNoFormatKeyword();

  // `verbose` stays on because `errors.ts` reads `data` from each error. The runtime validators
  // are compiled without annotations, which only add weight (see `stripAnnotations`).
  const ajv = createAjv({ allErrors: true, withoutAnnotations: true });
  for (const spec of plan.specs) {
    if (spec.derivedSchema) {
      ajv.addSchema(stripAnnotations(spec.derivedSchema));
    }
  }

  const standalone = new Map<string, StandaloneModule>();
  for (const spec of plan.specs) {
    standalone.set(
      spec.modulePath,
      toRuntimeImports(standaloneCode(ajv, { validate: spec.schemaId })),
    );
  }
  const { modules: validatorModules, shared } = shareDeclarations(standalone, SHARED_MODULE_PATH);
  const modules: ValidatorModules = new Map();
  for (const [modulePath, code] of validatorModules) {
    modules.set(modulePath, GENERATED_HEADER + code);
  }
  if (shared !== null) {
    modules.set(SHARED_MODULE_PATH, GENERATED_HEADER + shared);
  }
  modules.set('metadata', buildMetadataModule());
  modules.set('sync', buildSyncModule(plan));
  modules.set('lazy', buildLazyModule(plan));
  modules.set('testing/form-validator', buildFormValidatorModule());
  return modules;
}

function createAjv(options: { allErrors: boolean; withoutAnnotations?: boolean }): Ajv2020 {
  const ajv = new Ajv2020({
    allErrors: options.allErrors,
    strict: false,
    verbose: true,
    inlineRefs: false,
    code: { source: true, esm: true },
  });
  const registeredSchemaIds = new Set<string>();
  for (const schema of ALL_SCHEMAS) {
    if (typeof schema.$id === 'string' && !registeredSchemaIds.has(schema.$id)) {
      registeredSchemaIds.add(schema.$id);
      ajv.addSchema(options.withoutAnnotations ? stripAnnotations(schema) : schema);
    }
  }
  return ajv;
}

/**
 * The whole-form validator the runtime used before the walk became the only source of truth.
 * The differential test compares both on a corpus of forms. It keeps the annotations, so the
 * test also checks that stripping them changes nothing. `formValidator` reports every error;
 * `formValidatorFirstError` stops at the first one, which is much faster on deeply nested forms
 * (the widget `oneOf` validates every layout branch against the same children) and is enough to
 * know whether the form is valid.
 */
function buildFormValidatorModule(): string {
  const allErrors = toRuntimeImports(
    standaloneCode(createAjv({ allErrors: true }), { formValidator: FORM_SCHEMA.$id }),
  );
  const firstError = toRuntimeImports(
    standaloneCode(createAjv({ allErrors: false }), { formValidatorFirstError: FORM_SCHEMA.$id }),
  );
  // Both standalone outputs declare the same function names, so each one gets its own scope.
  const scoped = (body: string, exportName: string): string =>
    `export const ${exportName} = (() => {\n` +
    `${body.replace('"use strict";', '').replace(`export const ${exportName} =`, 'const validate =')}\n` +
    `return validate;\n})();\n`;
  return (
    GENERATED_HEADER +
    [...new Set([...allErrors.imports, ...firstError.imports])].join('') +
    scoped(allErrors.body, 'formValidator') +
    scoped(firstError.body, 'formValidatorFirstError')
  );
}

/**
 * ajv calls its runtime helpers (`ucs2length`, `equal`, ...) with
 * `require("ajv/dist/runtime/<name>").default`, which an ES module does not have. Each call
 * becomes an import of the helper, so the helpers stay shared between modules instead of being
 * copied into each one. The helpers are CommonJS: in Node the namespace's `default` is
 * `module.exports`, while bundlers resolve it to `exports.default`, hence the two lookups.
 */
export function toRuntimeImports(code: string): { imports: string[]; body: string } {
  const imports: string[] = [];
  const body = code.replace(
    /\brequire\(\s*"ajv\/dist\/runtime\/([A-Za-z0-9]+)"\s*\)\.default/g,
    (_match, helper: string) => {
      const binding = `ajvRuntime_${helper}`;
      const statement =
        `import * as ${binding}Module from "ajv/dist/runtime/${helper}.js";\n` +
        `const ${binding} = ${binding}Module.default?.default ?? ${binding}Module.default;\n`;
      if (!imports.includes(statement)) imports.push(statement);
      return binding;
    },
  );
  assertNoRequireCalls(body);
  return { imports, body };
}

// An ES module has no `require`. A require that is not a runtime helper must be handled here and
// not fail later in Node, in a Worker or in a browser.
function assertNoRequireCalls(code: string): void {
  const requireCalls = new Set(code.match(/\brequire\(\s*["'][^"']*["']\s*\)/g));
  if (requireCalls.size > 0) {
    throw new Error(
      `The generated validators call require, which an ES module does not have: ${[...requireCalls].join(', ')}`,
    );
  }
}

// The generator does not register ajv-formats. A `format` keyword would then be ignored and a
// validator would accept values the runtime Ajv rejected.
function assertNoFormatKeyword(): void {
  const visit = (node: unknown): boolean => {
    if (node === null || typeof node !== 'object') {
      return false;
    }
    if (Array.isArray(node)) {
      return node.some(visit);
    }
    return Object.entries(node).some(
      ([key, value]) => (key === 'format' && typeof value === 'string') || visit(value),
    );
  };
  if (visit(ALL_SCHEMAS)) {
    throw new Error(
      'A schema uses the "format" keyword. Register ajv-formats in the validator generator.',
    );
  }
}

// Module paths become file names: they must be safe, and unique on a case-insensitive file system.
function assertModulePaths(plan: StandaloneValidatorPlan): void {
  const seen = new Map<string, string>();
  for (const spec of plan.specs) {
    if (!MODULE_PATH_PATTERN.test(spec.modulePath)) {
      throw new Error(`"${spec.modulePath}" is not a valid module path`);
    }
    const folded = spec.modulePath.toLowerCase();
    const other = seen.get(folded);
    if (other !== undefined) {
      throw new Error(`"${spec.modulePath}" and "${other}" differ only in case`);
    }
    seen.set(folded, spec.modulePath);
  }
}

function buildMetadataModule(): string {
  const metadata = planValidatorMetadata();
  return (
    GENERATED_HEADER +
    Object.entries(metadata)
      .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`)
      .join('')
  );
}

function table(entries: [string, string][]): string {
  return `{\n${entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${value},`).join('\n')}\n}`;
}

function buildSyncModule(plan: StandaloneValidatorPlan): string {
  const bindingByModulePath = new Map<string, string>();
  const imports: string[] = [];
  for (const [index, spec] of plan.specs.entries()) {
    const binding = `v${index}`;
    bindingByModulePath.set(spec.modulePath, binding);
    imports.push(`import { validate as ${binding} } from "./${spec.modulePath}.js";\n`);
  }
  const bindings = (modulePathByKey: Record<string, string>): string =>
    table(
      Object.entries(modulePathByKey).map(([key, modulePath]) => [
        key,
        bindingByModulePath.get(modulePath)!,
      ]),
    );
  return (
    GENERATED_HEADER +
    imports.join('') +
    `export const rootValidator = ${bindingByModulePath.get(plan.rootModulePath)};\n` +
    `export const chunkRefValidator = ${bindingByModulePath.get(plan.chunkRefModulePath)};\n` +
    `export const SHALLOW_WIDGET_VALIDATORS = ${bindings(plan.shallowModulePathByWidgetType)};\n` +
    `export const VALIDATOR_BRANCH_VALIDATORS = ${bindings(plan.branchModulePathByValidatorType)};\n` +
    `export const CUSTOM_WIDGET_VALIDATORS = ${bindings(plan.customModulePathByKind)};\n`
  );
}

function buildLazyModule(plan: StandaloneValidatorPlan): string {
  // A literal path in each `import()` lets bundlers split every validator into its own chunk.
  const loader = (modulePath: string): string =>
    `() => import("./${modulePath}.js").then((m) => m.validate)`;
  const loaders = (modulePathByKey: Record<string, string>): string =>
    table(Object.entries(modulePathByKey).map(([key, modulePath]) => [key, loader(modulePath)]));
  return (
    GENERATED_HEADER +
    `export const loadRootValidator = ${loader(plan.rootModulePath)};\n` +
    `export const loadChunkRefValidator = ${loader(plan.chunkRefModulePath)};\n` +
    `export const SHALLOW_WIDGET_LOADERS = ${loaders(plan.shallowModulePathByWidgetType)};\n` +
    `export const VALIDATOR_BRANCH_LOADERS = ${loaders(plan.branchModulePathByValidatorType)};\n` +
    `export const CUSTOM_WIDGET_LOADERS = ${loaders(plan.customModulePathByKind)};\n`
  );
}
